let currentLang = (navigator.language || "zh").toLowerCase().startsWith("zh") ? "zh" : "en";

export function setLocale(locale) {
  if (!locale) return;
  const low = String(locale).toLowerCase();
  currentLang = low.startsWith("zh") ? "zh" : "en";
  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : "en";
  applyDomI18n();
}

export function getLang() {
  return currentLang;
}

export function t(key) {
  return (STRINGS[currentLang] && STRINGS[currentLang][key]) || STRINGS.en[key] || key;
}

export function thinkingLabel(val) {
  const key = val ? "th_" + String(val).toLowerCase() : "th_default";
  return t(key) !== key ? t(key) : val;
}

export function statusLabel(status) {
  const key = "st_" + String(status || "");
  return t(key) !== key ? t(key) : (status || "unknown");
}

export function applyDomI18n() {
  for (const node of document.querySelectorAll("[data-i18n]")) {
    const key = node.getAttribute("data-i18n");
    if (key) node.textContent = t(key);
  }
  for (const node of document.querySelectorAll("[data-i18n-placeholder]")) {
    const key = node.getAttribute("data-i18n-placeholder");
    if (key) node.setAttribute("placeholder", t(key));
  }
}
